
# Bitwise AND  &
print (5 & 3)   # Output: 1
''' 
  0101  (Decimal 5)
& 0011  (Decimal 3)
--------
  0001  (Decimal 1)

'''

# Bitwise OR |
print (5 | 3)   # Output: 7

""" 

  0101  (Decimal 5)
| 0011  (Decimal 3)
------
  0111  (Decimal 7)

"""
# Bitwise XOR ^
# The caret symbol (^) represents the bitwise XOR (Exclusive OR) operator
print(5 ^ 3)    # # Output: 6

''' 
  0101  (Decimal 5)
^ 0011  (Decimal 3)
------
  0110  (Decimal 6)
'''
